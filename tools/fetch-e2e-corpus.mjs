const log = (...m) => console.log('[fetch-e2e-corpus]', ...m);
const err = (...m) => console.error('[fetch-e2e-corpus]', ...m);
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

function ghHeaders() {
  const h = { Accept: 'application/vnd.github+json', 'User-Agent': 'vviewer-e2e-corpus' };
  if (process.env.GITHUB_TOKEN) h.Authorization = `Bearer ${process.env.GITHUB_TOKEN}`;
  return h;
}

/** git blob sha1（与 trees API 清单的 sha 比对，校验下载内容未损坏） */
function gitBlobSha(buf) {
  return createHash('sha1').update(`blob ${buf.length}\0`).update(buf).digest('hex');
}

const sha256 = (data) => createHash('sha256').update(data).digest('hex');

/** 下载单个 raw 文件：非 2xx 或 HTML 错误页均按失败，共尝试 MAX_ATTEMPTS 次（线性退避）。
 * HTML 嗅探例外：部分语料正文本身就是 HTML 文档（linguist Blade 样本以 <!DOCTYPE html>
 * 开头）——git blob sha 与清单一致即可证非拦截页，sha 不一致（或清单无 sha）才判错误页。 */
async function fetchRaw(source, path, expectedSha) {
  // 逐段编码：防路径中 '#'/空格等改变 URL 语义（防御性处理）
  const url =
    `https://raw.githubusercontent.com/${source.repo}/${source.commit}/` +
    path.split('/').map(encodeURIComponent).join('/');
  let lastErr;
  for (let attempt = 1; attempt <= MAX_ATTEMPTS; attempt++) {
    if (attempt > 1) await sleep(300 * attempt);
    try {
      const res = await fetch(url, { headers: ghHeaders() });
      if (!res.ok) throw new Error(`HTTP ${res.status}`);
      const buf = Buffer.from(await res.arrayBuffer());
      if (buf.subarray(0, 14).toString('latin1').toLowerCase() === '<!doctype html') {
        if (!expectedSha || gitBlobSha(buf) !== expectedSha) {
          throw new Error('返回 HTML 错误页（疑似拦截/限流页）');
        }
      }
      return buf;
    } catch (e) {
      lastErr = e;
    }
  }
  throw lastErr;
}

/** 路径必须可安全映射进语料目录内（trees API 正常返回相对路径，防御异常值越界写） */
function safeSegments(path) {
  const segs = path.split('/');
  if (path.startsWith('/') || segs.some((s) => s === '' || s === '.' || s === '..')) return null;
  return segs;
}

async function apiJson(url) {
  const res = await fetch(url, { headers: ghHeaders() });
  if (!res.ok) throw new Error(`HTTP ${res.status}（${url}）`);
  return res.json();
}

/**
 * 列举一个 tree（优先 recursive=1 一次拿全；响应 truncated 即改分层 BFS 逐目录列举，
 * 目录级仍 truncated 记失败清单——绝不静默截断）。返回 blob 相对 dirRoot 的路径。
 */
async function listTree(repo, treeRef, failures) {
  const tree = await apiJson(`${API}/repos/${repo}/git/trees/${treeRef}?recursive=1`);
  const toBlob = (path, e) => ({ path, size: e.size, sha: e.sha });
  if (!tree.truncated) {
    return tree.tree.filter((e) => e.type === 'blob').map((e) => toBlob(e.path, e));
  }
  log('recursive 列举 truncated，改分层逐目录列举');
  const blobs = [];
  const queue = [{ sha: treeRef, dir: '' }];
  while (queue.length > 0) {
    const { sha, dir } = queue.shift();
    const t = await apiJson(`${API}/repos/${repo}/git/trees/${sha}`);
    if (t.truncated) {
      failures.push({ path: dir || '<root>', reason: 'tree API 目录级 truncated（清单不完整）' });
      continue;
    }
    for (const e of t.tree) {
      const p = dir ? `${dir}/${e.path}` : e.path;
      if (e.type === 'blob') blobs.push(toBlob(p, e));
      else if (e.type === 'tree') queue.push({ sha: e.sha, dir: p });
    }
  }
  return blobs;
}

/**
 * 列举一个源的候选文件清单：逐段下钻解析 pathPrefix 子树（根树只列直接子项，多段前缀
 * 须逐段取子树 sha）→ 递归列举（含 truncated 兜底）。返回 { entries, fatal }，fatal 表示
 * 清单级失败（无法继续该源下载）。
 */
async function listSource(source) {
  const failures = [];
  if (source.pathPrefix === '') {
    const entries = await listTree(source.repo, source.commit, failures);
    return { entries, failures, fatal: null };
  }
  let sha = source.commit;
  let walked = '';
  for (const seg of source.pathPrefix.split('/')) {
    const t = await apiJson(`${API}/repos/${source.repo}/git/trees/${sha}`);
    if (t.truncated) {
      return { entries: [], failures, fatal: `树 "${walked || '<root>'}" truncated（前缀解析不可靠）` };
    }
    const entry = t.tree.find((e) => e.path === seg);
    if (!entry) {
      return { entries: [], failures, fatal: `pathPrefix "${source.pathPrefix}" 不存在于该 commit（缺 "${walked ? `${walked}/${seg}` : seg}"）` };
    }
    if (entry.type !== 'tree') {
      return { entries: [], failures, fatal: `pathPrefix "${source.pathPrefix}" 非目录` };
    }
    sha = entry.sha;
    walked = walked ? `${walked}/${seg}` : seg;
  }
  const blobs = await listTree(source.repo, sha, failures);
  // 子树内路径 → 仓库内相对路径（raw 下载与 manifest path 均用仓库内口径）
  const entries = blobs.map((e) => ({ ...e, path: `${source.pathPrefix}/${e.path}` }));
  return { entries, failures, fatal: null };
}

/** 有限并发执行（保持完成结果按入参顺序回填，保证 manifest 顺序确定） */
async function runPool(items, worker) {
  let next = 0;
  const lanes = Array.from({ length: Math.min(CONCURRENCY, items.length) }, async () => {
    while (next < items.length) {
      const idx = next++;
      await worker(items[idx], idx);
    }
  });
  await Promise.all(lanes);
}

async function main() {
  const sources = []; // manifest.sources，按 SOURCES 表顺序
  const failures = []; // manifest.failures，元素 { source, path, reason }
  let hardFail = false; // 清单拉取失败 / 清单为空 → 非 0 退出
  let totalDownloaded = 0;
  let totalSkipped = 0;

  for (const source of SOURCES) {
    log(`── 源 ${source.id}：${source.repo}@${source.commit.slice(0, 8)}… 前缀 "${source.pathPrefix || '<整仓>'}"`);
    // 1. 列清单
    let listed;
    try {
      listed = await listSource(source);
    } catch (e) {
      err(`源 ${source.id} 清单拉取失败：${e.message}`);
      failures.push({ source: source.id, path: '<tree>', reason: `清单拉取失败：${e.message}` });
      hardFail = true;
      continue;
    }
    for (const f of listed.failures) failures.push({ source: source.id, path: f.path, reason: f.reason });
    if (listed.fatal) {
      err(`源 ${source.id} 清单不可用：${listed.fatal}`);
      failures.push({ source: source.id, path: '<tree>', reason: listed.fatal });
      hardFail = true;
      continue;
    }
    const matched = listed.entries.filter(
      (e) => source.extensions.some((ext) => e.path.endsWith(ext)) && (!source.maxBytes || e.size <= source.maxBytes)
    );
    if (matched.length === 0) {
      err(`源 ${source.id} 清单中无匹配扩展名（${source.extensions.join(' ')}）的文件，中止该源`);
      failures.push({ source: source.id, path: '<tree>', reason: '清单为空（无匹配扩展名文件）' });
      hardFail = true;
      continue;
    }
    // 2. maxFiles 确定性截断：按 tree 顺序取前 N，截断标志入 manifest
    const truncatedByMaxFiles = matched.length > source.maxFiles;
    const capped = matched.slice(0, source.maxFiles);
    log(`清单：匹配 ${matched.length} 个，取前 ${capped.length}（maxFiles=${source.maxFiles}${truncatedByMaxFiles ? '，截断' : ''}）`);

    // 3. 有限并发逐个落位（幂等：已存在且 size 与清单一致则跳过）
    const results = new Array(capped.length);
    let downloaded = 0;
    let skipped = 0;
    await runPool(capped, async (entry, idx) => {
      const segs = safeSegments(entry.path);
      if (!segs) {
        failures.push({ source: source.id, path: entry.path, reason: '非法路径' });
        return;
      }
      const dest = join(corpusRoot, source.id, ...segs);
      if (existsSync(dest) && statSync(dest).size === entry.size) {
        skipped++;
        results[idx] = { path: entry.path, size: entry.size, sha256: sha256(readFileSync(dest)) };
        log(`skipped: ${source.id}/${entry.path}（size 一致）`);
        return;
      }
      try {
        const buf = await fetchRaw(source, entry.path, entry.sha);
        const gitSha = gitBlobSha(buf);
        if (entry.sha && gitSha !== entry.sha) {
          throw new Error(`git blob sha 不一致（期望 ${entry.sha.slice(0, 8)}…，实得 ${gitSha.slice(0, 8)}…）`);
        }
        mkdirSync(dirname(dest), { recursive: true });
        writeFileSync(dest, buf);
        downloaded++;
        results[idx] = { path: entry.path, size: buf.length, sha256: sha256(buf) };
        log(`downloaded: ${source.id}/${entry.path}（${buf.length} bytes）`);
      } catch (e) {
        failures.push({ source: source.id, path: entry.path, reason: String(e.message || e) });
        err(`失败（${MAX_ATTEMPTS} 次尝试后）：${source.id}/${entry.path} — ${e.message}`);
      }
    });
    totalDownloaded += downloaded;
    totalSkipped += skipped;
    sources.push({
      id: source.id,
      repo: source.repo,
      commit: source.commit,
      truncatedByMaxFiles,
      files: results.filter(Boolean)
    });
  }

  // 4. manifest（语料根目录，随目录一并 gitignore）
  const bySource = Object.fromEntries(sources.map((s) => [s.id, s.files.length]));
  const total = sources.reduce((n, s) => n + s.files.length, 0);
  const manifest = {
    generatedAt: new Date().toISOString(),
    sources,
    counts: { total, bySource },
    failures
  };
  mkdirSync(corpusRoot, { recursive: true });
  const manifestPath = join(corpusRoot, 'manifest.json');
  writeFileSync(manifestPath, JSON.stringify(manifest, null, 2) + '\n');

  // 5. 汇总与退出码：任一源清单失败/清单为空（上方已置 hardFail）或全部文件失败 → 非 0；
  //    部分文件失败 → 失败清单写入 manifest.failures 并告警，不阻断（缺个别语料由 e2e 用例自身暴露）
  const landed = totalDownloaded + totalSkipped;
  log(`完成：共 ${total} 个文件（下载 ${totalDownloaded}，幂等跳过 ${totalSkipped}，失败 ${failures.length}）；manifest → ${manifestPath}`);
  for (const s of sources) {
    log(`  - ${s.id}: ${s.files.length} 个${s.truncatedByMaxFiles ? '（maxFiles 截断）' : ''}`);
  }
  if (failures.length > 0) {
    err(`${failures.length} 条失败（已记入 manifest.failures）：`);
    for (const f of failures) err(`  - [${f.source}] ${f.path}: ${f.reason}`);
  }
  if (hardFail || landed === 0) {
    if (!hardFail) err('全部文件下载失败，语料不可用');
    process.exitCode = 1;
  }
}

await main();
